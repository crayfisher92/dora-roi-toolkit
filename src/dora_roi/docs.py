"""Generate documentation from the code (kept in sync by a test).

``python -m dora_roi.docs`` rewrites ``docs/REGULATORY_MAPPING.md`` and
``docs/DATA_DICTIONARY.md``.
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from dora_roi.io.tables import KIND_HINTS
from dora_roi.model import ALL_CODELISTS, TEMPLATE_MODELS
from dora_roi.validation import Category, rules_catalogue
from dora_roi.validation.references import DORA, ITS, REFERENCES

CATEGORY_TITLES = {
    Category.IMPORT: "Import checks (IMP)",
    Category.FIELD: "Field-level checks (FLD)",
    Category.REFERENTIAL: "Cross-template referential integrity (XRF)",
    Category.SUPPLY_CHAIN: "ICT supply chain / subcontracting (SC)",
    Category.BUSINESS: "Business and conditional rules (BUS)",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def regulatory_mapping_markdown() -> str:
    """Markdown table linking every rule to the provisions it supports."""
    rules = rules_catalogue()
    lines = [
        "# Regulatory mapping",
        "",
        "<!-- Generated by `python -m dora_roi.docs`; do not edit by hand. -->",
        "",
        "This document links every validation rule of the toolkit to the provision of "
        f"{DORA} or of the {ITS} that it supports. It is generated from the rule registry, "
        "so it always matches the code.",
        "",
        "> The references express *which obligation a rule helps evidence*; they are the "
        "authors' interpretation (see [ASSUMPTIONS.md](ASSUMPTIONS.md), in particular A-VAL-* "
        "and A-REG-01) and are not the official EBA validation rules.",
        "",
        f"**{len(rules)} rules.** Severity: *error* blocks a clean submission, *warning* needs "
        "review, *info* is for awareness.",
        "",
    ]
    by_cat: dict[Category, list[object]] = defaultdict(list)
    for r in rules:
        by_cat[r.category].append(r)
    for cat in Category:
        if cat not in by_cat:
            continue
        lines += [f"## {CATEGORY_TITLES[cat]}", "",
                  "| Rule | Severity | Check | Templates | Supports |", "|---|---|---|---|---|"]
        for r in rules:
            if r.category is not cat:
                continue
            tpl = ", ".join(r.templates) if len(r.templates) <= 5 else "all templates"
            lines.append(
                f"| `{r.id}` | {r.severity.value} | **{_cell(r.title)}** – "
                f"{_cell(r.description)} | {tpl or '—'} | {_cell('; '.join(r.references))} |"
            )
        lines.append("")
    lines += ["## Provisions referenced", "", "| Reference | Meaning |", "|---|---|"]
    used = {ref for r in rules for ref in r.references}
    for ref, text in REFERENCES.items():
        if ref in used:
            lines.append(f"| {ref} | {_cell(text)} |")
    lines += ["", "## Coverage by provision", ""]
    by_ref: dict[str, list[str]] = defaultdict(list)
    for r in rules:
        for ref in r.references:
            by_ref[ref].append(r.id)
    for ref in REFERENCES:
        if ref in by_ref:
            lines.append(f"- **{ref}**: {', '.join(f'`{x}`' for x in by_ref[ref])}")
    lines.append("")
    return "\n".join(lines)


def data_dictionary_markdown() -> str:
    """Markdown description of every template, column and code list."""
    lines = [
        "# Data dictionary",
        "",
        "<!-- Generated by `python -m dora_roi.docs`; do not edit by hand. -->",
        "",
        "Templates and columns as modelled in `dora_roi.model.templates`. Requirement: "
        "**M** mandatory, **C** conditional, **O** optional. See "
        "[ASSUMPTIONS.md](ASSUMPTIONS.md) A-TPL-*.",
        "",
    ]
    for model in TEMPLATE_MODELS:
        lines += [f"## {model.TEMPLATE} – {model.TITLE}", "",
                  f"Python model: `{model.__name__}` · key: "
                  f"{', '.join(f'`{k}`' for k in model.KEY)}", "",
                  "| Column | Attribute | Label | Req. | Type | Condition |",
                  "|---|---|---|---|---|---|"]
        for spec in model.columns():
            col = spec.col
            kind = (f"Code list `{col.codelist.__name__}`" if col.codelist
                    else KIND_HINTS[col.kind])
            lines.append(f"| `{spec.code}` | `{spec.attr}` | {_cell(spec.label)} | "
                         f"{col.requirement.value} | {kind} | {_cell(col.condition or '')} |")
        lines.append("")
    lines += ["## Code lists", ""]
    for cl in ALL_CODELISTS:
        lines += [f"### `{cl.__name__}`", "", "| Code | Label |", "|---|---|"]
        lines += [f"| `{m.value}` | {_cell(m.label)} |" for m in cl]
        lines.append("")
    return "\n".join(lines)


def write_docs(folder: str | Path = "docs") -> list[Path]:
    out = Path(folder)
    out.mkdir(parents=True, exist_ok=True)
    targets = {
        out / "REGULATORY_MAPPING.md": regulatory_mapping_markdown(),
        out / "DATA_DICTIONARY.md": data_dictionary_markdown(),
    }
    for path, text in targets.items():
        path.write_text(text, encoding="utf-8")
    return list(targets)


if __name__ == "__main__":  # pragma: no cover
    for p in write_docs():
        print(f"wrote {p}")
