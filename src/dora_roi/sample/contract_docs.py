def write_sample_contract(path: Path) -> Path:
    """Write the sample contract; the format follows the suffix (.txt, .docx or .pdf)."""
    suffix = path.suffix.lower()
    path.parent.mkdir(parents=True, exist_ok=True)
    if suffix == ".docx":
        path.write_bytes(docx_bytes(SAMPLE_CONTRACT_TEXT))
    elif suffix == ".pdf":
        path.write_bytes(pdf_bytes(SAMPLE_CONTRACT_TEXT))
    else:
        path.write_text(SAMPLE_CONTRACT_TEXT, encoding="utf-8")
    return path


# --------------------------------------------------------------------------- DOCX


def docx_bytes(text: str) -> bytes:
    """A minimal valid .docx with one paragraph per line (numbered headings in bold)."""
    paragraphs = []
    for line in text.splitlines():
        heading = bool(line) and ((line[0].isdigit() and ". " in line[:4]) or line.isupper())
        run_props = "<w:rPr><w:b/></w:rPr>" if heading else ""
        paragraphs.append(f'<w:p><w:r>{run_props}<w:t xml:space="preserve">{escape(line)}'
                          "</w:t></w:r></w:p>")
    document = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        f"<w:body>{''.join(paragraphs)}</w:body></w:document>")
    content_types = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" '
        'ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/word/document.xml" ContentType="application/'
        'vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>')
    rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/'
        'relationships/officeDocument" Target="word/document.xml"/></Relationships>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("[Content_Types].xml", content_types)
        zf.writestr("_rels/.rels", rels)
        zf.writestr("word/document.xml", document)
    return buf.getvalue()


# --------------------------------------------------------------------------- PDF


def _pdf_string(line: str) -> bytes:
    raw = line.encode("cp1252", errors="replace")
    out = bytearray(b"(")
    for b in raw:
        if b in (0x28, 0x29, 0x5C):  # ( ) \
            out += b"\\" + bytes([b])
        elif b > 126 or b < 32:
            out += f"\\{b:03o}".encode()
        else:
            out.append(b)
    return bytes(out + b")")


def pdf_bytes(text: str, lines_per_page: int = 56, width: int = 96) -> bytes:
    """A minimal text-only PDF (Helvetica, WinAnsi) that text extractors can read."""
    lines: list[str] = []
    for para in text.splitlines():
        lines += textwrap.wrap(para, width) or [""]
    pages = [lines[i:i + lines_per_page] for i in range(0, len(lines), lines_per_page)] or [[]]
    objects: list[bytes] = []
    font_id = 3
    page_ids = []
    next_id = 4
    content: list[tuple[int, int, bytes]] = []
    for page in pages:
        stream = bytearray(b"BT /F1 10 Tf 13 TL 56 790 Td\n")
        for line in page:
            stream += _pdf_string(line) + b" Tj T*\n"
        stream += b"ET"
        page_ids.append(next_id)
        content.append((next_id, next_id + 1, bytes(stream)))
        next_id += 2
    objects.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    kids = " ".join(f"{i} 0 R" for i in page_ids)
    objects.append(f"<< /Type /Pages /Kids [{kids}] /Count {len(page_ids)} >>".encode())
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica "
                   b"/Encoding /WinAnsiEncoding >>")
    for page_id, stream_id, body in content:
        objects.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources "
                       f"<< /Font << /F1 {font_id} 0 R >> >> /Contents {stream_id} 0 R >>"
                       .encode())
        objects.append(f"<< /Length {len(body)} >>\nstream\n".encode() + body
                       + b"\nendstream")
        assert page_id + 1 == stream_id
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, obj in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode() + obj + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode()
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += (f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n"
            .encode())
    return bytes(out)
