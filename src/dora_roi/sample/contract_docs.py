"""A fictional sample ICT services contract, written as .txt, .docx or .pdf.

The agreement between *Alpenrand Bank (Europe) AG* and *Mobilio Digital Banking GmbH*
(arrangement ``AR-DE-0057`` of the sample register, supporting the critical function
"Digital and mobile banking channels") is deliberately incomplete in the way contracts
signed before DORA often are: no TLPT clause, audit rights for the bank only (not for the
competent authority), no exit transition period. It drives the demo of the document upload
and keyword suggestions. The .docx and .pdf writers are minimal and dependency-free.
"""

