import io
import textwrap
import zipfile
from pathlib import Path
from xml.sax.saxutils import escape

SAMPLE_CONTRACT_REF = "AR-DE-0057"
SAMPLE_CONTRACT_NAME = "Mobilio-Digital-Banking-Services-Agreement.docx"

