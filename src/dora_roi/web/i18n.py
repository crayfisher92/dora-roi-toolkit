def translator(lang: str) -> Callable[..., str]:
    catalogue = MESSAGES.get(lang, MESSAGES[DEFAULT_LANGUAGE])
    fallback = MESSAGES[DEFAULT_LANGUAGE]

    def t(key: str, **params: object) -> str:
        text = catalogue.get(key) or fallback.get(key) or key
        return text.format(**params) if params else text

    return t


def pick_language(query: str | None, cookie: str | None, accept: str | None) -> str:
    for candidate in (query, cookie):
        if candidate in LANGUAGES:
            return candidate
    if accept:
        for part in accept.split(","):
            code = part.split(";")[0].strip().lower()[:2]
            if code in LANGUAGES:
                return code
    return DEFAULT_LANGUAGE
