"""Regenerate the generated tables of ``src/dora_roi/model/eba_codes.py`` from ``reference/eba``.

Reads the official EBA workbooks with the standard library only (an ``.xlsx`` is a zip of XML
parts) and rewrites everything below the ``GENERATED`` marker of ``eba_codes.py``: the B_06.01
licensed activities and the DPM country and currency members. The hand-maintained part above
the marker (code-list mapping) is left untouched.

Usage::

    python scripts/gen_eba_codes.py            # rewrite eba_codes.py
    python scripts/gen_eba_codes.py --check    # exit 1 if it is out of date
"""

from __future__ import annotations

import re
import sys
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "reference" / "eba"
TARGET = ROOT / "src" / "dora_roi" / "model" / "eba_codes.py"
DROPDOWNS = REF / "list-of-possible-values-2025-03-03.xlsx"
LICENSED = REF / "licensed-activities-dpm-4.0.xlsx"
MARKER = "# ---- GENERATED by scripts/gen_eba_codes.py from reference/eba - do not edit below ----"

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
REL = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"


def _col(ref: str) -> int:
    n = 0
    for ch in re.match(r"[A-Z]+", ref).group(0):  # type: ignore[union-attr]
        n = n * 26 + ord(ch) - 64
    return n - 1


def read_rows(path: Path) -> list[list[str]]:
    """All non-empty rows of all sheets, as lists of cell texts."""
    rows: list[list[str]] = []
    with zipfile.ZipFile(path) as z:
        shared: list[str] = []
        if "xl/sharedStrings.xml" in z.namelist():
            strings = ET.fromstring(z.read("xl/sharedStrings.xml"))
            for si in strings.findall("m:si", NS):
                shared.append("".join(t.text or "" for t in si.iter(f"{{{NS['m']}}}t")))
        rels = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
        target = {r.get("Id"): r.get("Target") or "" for r in rels}
        book = ET.fromstring(z.read("xl/workbook.xml"))
        sheets = book.find("m:sheets", NS)
        for sheet in sheets if sheets is not None else []:
            part = target[sheet.get(REL)].lstrip("/")
            part = part if part.startswith("xl/") else f"xl/{part}"
            for row in ET.fromstring(z.read(part)).iter(f"{{{NS['m']}}}row"):
                cells: dict[int, str] = {}
                for c in row.findall("m:c", NS):
                    v = c.find("m:v", NS)
                    if c.get("t") == "s" and v is not None and v.text:
                        text = shared[int(v.text)]
                    elif c.get("t") == "inlineStr":
                        text = "".join(t.text or "" for t in c.iter(f"{{{NS['m']}}}t"))
                    else:
                        text = v.text if v is not None and v.text else ""
                    if text.strip():
                        cells[_col(c.get("r") or "A1")] = " ".join(text.split())
                if cells:
                    rows.append([cells.get(i, "") for i in range(max(cells) + 1)])
    return rows


def _wrap(items: list[str], per: int) -> str:
    return "\n".join("    " + " ".join(items[i:i + per]) for i in range(0, len(items), per))


def generate() -> str:
    text = "\n".join("|".join(r) for r in read_rows(DROPDOWNS))
    countries = sorted(set(re.findall(r"eba_GA:([A-Z]{2})\b", text)))
    currencies = sorted(set(re.findall(r"eba_CU:([A-Z]{3})\b", text)))
    activities: dict[str, list[str]] = {}
    for row in read_rows(LICENSED):
        # columns: _, entity type, entity code, definition, regulation, activity code, label …
        if len(row) > 6 and row[5].startswith("eba_TA:"):
            label = row[6].strip().strip('"').strip()
            labels = activities.setdefault(row[5], [])
            if label and label not in labels:
                labels.append(label)
    lines = [MARKER, "",
             "#: B_06.01 c0020 - ``(member, label)``; a member may appear with several label "
             "variants.",
             "LICENSED_ACTIVITIES: tuple[tuple[str, str], ...] = ("]
    for code in sorted(activities, key=lambda c: int(re.sub(r"\D", "", c.split(":")[1]))):
        lines += [f"    ({code!r}, {label!r})," for label in activities[code]]
    lines += [")", "",
              "#: Members of the DPM country hierarchy (``eba_GA:``) apart from ``x28`` and "
              "``qx2007``.",
              'EBA_COUNTRIES: frozenset[str] = frozenset("""', _wrap(countries, 25),
              '""".split())', "",
              "#: Members of the DPM currency hierarchy ``CU3_4_WITHOUT_X0`` (``eba_CU:``).",
              'EBA_CURRENCIES: frozenset[str] = frozenset("""', _wrap(currencies, 20),
              '""".split())', ""]
    return "\n".join(lines)


def main() -> int:
    current = TARGET.read_text(encoding="utf-8")
    head = current.split(MARKER, 1)[0]
    updated = head + generate()
    if "--check" in sys.argv:
        if updated != current:
            print(f"{TARGET} is out of date; run python scripts/gen_eba_codes.py")
            return 1
        return 0
    TARGET.write_text(updated, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
